function getValue(source, path) {
  return String(path)
    .split(".")
    .reduce((accumulator, key) => (accumulator && typeof accumulator === "object" ? accumulator[key] : undefined), source);
}

function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, key) => {
    if (!Object.prototype.hasOwnProperty.call(params, key)) return `{${key}}`;
    const value = params[key];
    return value == null ? "" : String(value);
  });
}

export function translate(language, key, params = {}) {
  const fallback = getValue(TRANSLATIONS.ru, key) ?? key;
  const template = getValue(TRANSLATIONS[language] || TRANSLATIONS.ru, key) ?? fallback;
  return interpolate(template, params);
}

